const int kGlyphCount = sizeof(kGlyphs) / sizeof(kGlyphs[0]);
const int kAdvance = 9; // 8 pixels of glyph + 1 column of spacing, pre-scale

const unsigned char* FindGlyph(char ch) {
    for (int i = 0; i < kGlyphCount; i++)
        if (kGlyphs[i].ch == ch) return kGlyphs[i].rows;
    return nullptr; // unknown character -> blank
}

void DrawChar8x8(SDL_Renderer* renderer, int x, int y, char ch, int scale) {
    const unsigned char* rows = FindGlyph(ch);
    if (!rows) return;

    for (int row = 0; row < 8; row++) {
        unsigned char bits = rows[row];
        for (int col = 0; col < 8; col++) {
            if (!(bits & (0x80 >> col))) continue;
            SDL_Rect px = { x + col * scale, y + row * scale, scale, scale };
            SDL_RenderFillRect(renderer, &px);
        }
    }
}

