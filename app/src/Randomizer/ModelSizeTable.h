// Mirrors the reference tool's lookup exactly: first table row whose
// namePrefix is a substring of modelName (`.Contains()`), else 0 (matching
// the reference's behavior of simply leaving originalModelValue/
// newModelValue at their initialized-to-0 default when nothing matches).
inline int64_t LookupModelSize(const std::string& modelName) {
    for (const auto& e : ModelSizeTable()) {
        if (modelName.find(e.namePrefix) != std::string::npos) return e.size;
    }
    return 0;
}

